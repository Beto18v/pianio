/**
 * Auto-generates the song library from MIDI files in public/pianosongs/.
 * Run before every build so adding a .mid file is enough — no code changes needed.
 *
 * Usage: node scripts/generate-song-library.mjs
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const PIANOSONGS_DIR = join(ROOT, 'public', 'pianosongs');
const METADATA_PATH = join(PIANOSONGS_DIR, 'metadata.json');
const OUTPUT_PATH = join(ROOT, 'src', 'app', 'core', 'song-library.generated.ts');

const DEFAULT_DIFFICULTY = 'Intermedio';

/** Normalize smart/curly quotes to straight quotes for reliable metadata matching */
const SMART_QUOTES = {
  '\u201c': '"', // left double
  '\u201d': '"', // right double
  '\u2018': "'", // left single
  '\u2019': "'", // right single
};

function normalizeQuotes(str) {
  return str.replace(/[\u201c\u201d\u2018\u2019]/g, (ch) => SMART_QUOTES[ch] ?? ch);
}

function slugify(filename) {
  const name = filename.replace(/\.mid$/i, '');
  return name
    .toLowerCase()
    .replace(/["'()]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function titleFromFilename(filename) {
  return filename.replace(/\.mid$/i, '').replace(/_/g, ' ');
}

function toValidJsonString(str) {
  return JSON.stringify(str);
}

/** Escape backticks and template literal interpolations for TS output */
function escapeTemplate(str) {
  return str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\${/g, '\\${');
}

function main() {
  // Read MIDI files
  const entries = readdirSync(PIANOSONGS_DIR, { withFileTypes: true });
  const midiFiles = entries
    .filter((e) => e.isFile() && /\.mid$/i.test(e.name))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b, 'en'));

  if (midiFiles.length === 0) {
    console.warn('⚠ No .mid files found in public/pianosongs/. Generating empty library.');
  }

  // Read metadata overrides
  let metadata = {};
  try {
    metadata = JSON.parse(readFileSync(METADATA_PATH, 'utf-8'));
  } catch {
    console.warn('⚠ No metadata.json found. All songs will use defaults.');
  }

  // Normalize metadata keys so smart quotes don't break matching
  const normalizedMetadata = {};
  for (const [key, value] of Object.entries(metadata)) {
    normalizedMetadata[normalizeQuotes(key)] = value;
  }

  // Generate entries
  const libraryEntries = midiFiles.map((filename) => {
    const lookupKey = normalizeQuotes(filename);
    const override = normalizedMetadata[lookupKey] ?? {};
    const id = slugify(filename);
    const title = override.title ?? titleFromFilename(filename);
    const artist = override.artist ?? 'Desconocido';
    const difficulty = override.difficulty ?? DEFAULT_DIFFICULTY;
    const featured = override.featured ?? false;
    const tags = override.tags ?? [];

    return {
      id,
      title,
      artist,
      assetPath: `/pianosongs/${filename}`,
      difficulty,
      ...(featured ? { featured: true } : {}),
      tags,
    };
  });

  // Generate TypeScript output
  const header = [
    '// AUTO-GENERATED by scripts/generate-song-library.mjs — DO NOT EDIT MANUALLY',
    '// Generated from public/pianosongs/ metadata.json + file listing',
    `// ${midiFiles.length} songs`,
    '',
    "import type { SongLibraryEntry } from './song-library.types';",
    '',
    'export const BUILT_IN_SONG_LIBRARY: ReadonlyArray<SongLibraryEntry> = [',
  ].join('\n');

  const footer = '\n] as const;\n';

  const body = libraryEntries
    .map((entry) => {
      const lines = [
        '  {',
        `    id: ${toValidJsonString(entry.id)},`,
        `    title: ${toValidJsonString(entry.title)},`,
        `    artist: ${toValidJsonString(entry.artist)},`,
        `    assetPath: ${toValidJsonString(entry.assetPath)},`,
        `    difficulty: ${toValidJsonString(entry.difficulty)},`,
      ];
      if (entry.featured) {
        lines.push('    featured: true,');
      }
      lines.push(
        `    tags: [${entry.tags.map((t) => toValidJsonString(t)).join(', ')}],`,
      );
      lines.push('  },');
      return lines.join('\n');
    })
    .join('\n\n');

  const output = header + '\n' + body + '\n' + footer;

  writeFileSync(OUTPUT_PATH, output, 'utf-8');
  console.log(`✅ Generated ${libraryEntries.length} song entries → ${OUTPUT_PATH}`);
}

main();
